CREATE TABLE event (
    id VARCHAR(255) PRIMARY KEY,
    max_participants INTEGER NOT NULL,
    date TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    title VARCHAR(255) NOT NULL,
    description VARCHAR(2000),
    certificate_requests_sent BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT ck_event_max_participants_positive CHECK (max_participants > 0)
);

CREATE TABLE subscription (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id VARCHAR(255) NOT NULL,
    participant_email VARCHAR(255) NOT NULL,
    participant_name VARCHAR(255),
    checkin_token VARCHAR(255) NOT NULL,
    checked_in_at TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT fk_subscription_event FOREIGN KEY (event_id) REFERENCES event (id),
    CONSTRAINT uk_subscription_event_email UNIQUE (event_id, participant_email),
    CONSTRAINT uk_subscription_checkin_token UNIQUE (checkin_token)
);

CREATE TABLE outbox_message (
    id VARCHAR(255) PRIMARY KEY,
    routing_key VARCHAR(255) NOT NULL,
    payload VARCHAR(4000) NOT NULL,
    status VARCHAR(20) NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    processed_at TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT ck_outbox_message_status CHECK (status IN ('PENDING', 'SENT', 'FAILED'))
);

CREATE INDEX idx_outbox_status_created ON outbox_message (status, created_at);
